"""Create the firmware signing key (run once, by the owner).

  python tools/keygen.py

Writes:
  keys/signing_key.pem   PRIVATE key. Never commit or share it (keys/ is git-ignored).
                         Keep a backup: without it you can't publish updates the
                         devices will accept (you'd have to reflash them over USB).
  src/signing_pubkey.h   Public key compiled into the firmware. Safe to commit.
"""
import os, sys
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
key_path = os.path.join(ROOT, "keys", "signing_key.pem")
hdr_path = os.path.join(ROOT, "src", "signing_pubkey.h")

if os.path.exists(key_path) and "--force" not in sys.argv:
    sys.exit(f"{key_path} already exists. Use --force to replace it (old devices will then reject new updates).")

os.makedirs(os.path.dirname(key_path), exist_ok=True)
key = ec.generate_private_key(ec.SECP256R1())
with open(key_path, "wb") as f:
    f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                              serialization.NoEncryption()))
pub = key.public_key().public_bytes(serialization.Encoding.PEM,
                                    serialization.PublicFormat.SubjectPublicKeyInfo).decode()
with open(hdr_path, "w") as f:
    f.write("#pragma once\n// Firmware update signing key (public half). Generated by tools/keygen.py.\n")
    f.write("static const char SIGNING_PUBKEY_PEM[] =\n")
    for line in pub.strip().splitlines():
        f.write(f'  "{line}\\n"\n')
    f.write(";\n")
print("private key:", key_path)
print("public key header:", hdr_path)
