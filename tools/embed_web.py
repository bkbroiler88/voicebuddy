"""Gzip web/index.html into src/web_index.h (runs automatically before each PlatformIO build).

The page ships inside the firmware, so a signed firmware update also updates the page.
"""
import gzip, os

try:
    Import("env")                                   # running as a PlatformIO pre-script
    ROOT = env.subst("$PROJECT_DIR")
except NameError:                                   # running by hand
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(ROOT, "web", "index.html")
dst = os.path.join(ROOT, "src", "web_index.h")

if os.path.exists(src):
    html = open(src, "rb").read()
else:
    html = b"<!doctype html><title>Voice Buddy</title><p>Web page not built yet.</p>"

gz = gzip.compress(html, compresslevel=9, mtime=0)
lines = []
for i in range(0, len(gz), 20):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
out = ("#pragma once\n// Generated by tools/embed_web.py from web/index.html. Do not edit.\n"
       "#include <stdint.h>\n#include <stddef.h>\n"
       f"static const uint8_t WEB_INDEX_GZ[] = {{\n" + "\n".join(lines) + "\n};\n"
       f"static const size_t WEB_INDEX_GZ_LEN = {len(gz)};\n")

old = open(dst).read() if os.path.exists(dst) else ""
if old != out:
    with open(dst, "w") as f:
        f.write(out)
    print(f"embed_web: {len(html)} bytes -> {len(gz)} bytes gzipped")
